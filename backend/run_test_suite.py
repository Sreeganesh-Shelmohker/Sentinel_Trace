# ---------------------------------------------------------------------------
# Pre-flight Health Check
# ---------------------------------------------------------------------------

def check_server_health(base_url: str) -> bool:
    """Verify that the FastAPI server is reachable before running tests."""
    health_url = f"{base_url}/health"
    try:
        resp = requests.get(health_url, timeout=3.0)
        return resp.status_code == 200 and resp.json().get("status") == "ok"
    except (requests.exceptions.ConnectionError, requests.exceptions.Timeout):
        return False
    except Exception:
        return False


# ---------------------------------------------------------------------------
# Table Formatter
# ---------------------------------------------------------------------------

def print_table(headers: List[str], rows: List[List[str]]) -> None:
    col_widths = [len(h) for h in headers]
    for row in rows:
        for i, cell in enumerate(row):
            col_widths[i] = max(col_widths[i], len(cell))

    sep = "+" + "+".join("-" * (w + 2) for w in col_widths) + "+"
    hdr = "|" + "|".join(f" {h:<{col_widths[i]}} " for i, h in enumerate(headers)) + "|"

    print(sep)
    print(hdr)
    print(sep)
    for row in rows:
        line = "|" + "|".join(f" {cell:<{col_widths[i]}} " for i, cell in enumerate(row)) + "|"
        print(line)
    print(sep)


# ---------------------------------------------------------------------------
# Test Runners
# ---------------------------------------------------------------------------

def run_guardrail_tests(base_url: str) -> Dict[str, Any]:
    url = f"{base_url}/guardrail/check"
    rows: List[List[str]] = []
    latencies: List[float] = []
    passed = 0

    for tc in GUARDRAIL_CASES:
        payload = {"prompt": tc["prompt"]}
        t0 = time.monotonic()
        resp = requests.post(url, json=payload, timeout=10.0)
        wall_lat = (time.monotonic() - t0) * 1000

        data = resp.json()
        actual = "BLOCKED" if data.get("blocked") else "ALLOWED"
        is_pass = actual == tc["expected"]
        status = "[PASS]" if is_pass else "[FAIL]"
        if is_pass:
            passed += 1

        # Use server-reported latency if available, fallback to wall-clock
        latency = float(data.get("latency_ms", wall_lat))
        latencies.append(latency)

        prompt_disp = tc["prompt"]
        if len(prompt_disp) > 36:
            prompt_disp = prompt_disp[:33] + "..."

        rows.append([
            tc["id"],
            tc["name"],
            prompt_disp,
            tc["expected"],
            actual,
            status,
            f"{latency:.1f} ms",
        ])

    headers = ["ID", "Case Name", "Prompt", "Expected", "Actual", "Status", "Latency"]
    return {
        "headers": headers,
        "rows": rows,
        "total": len(GUARDRAIL_CASES),
        "passed": passed,
        "latencies": latencies,
    }


def run_eval_tests(base_url: str) -> Dict[str, Any]:
    url = f"{base_url}/evaluate/context"
    rows: List[List[str]] = []
    latencies: List[float] = []
    passed = 0

    for tc in EVAL_CASES:
        payload = {"context": tc["context"], "response": tc["response"]}
        t0 = time.monotonic()
        resp = requests.post(url, json=payload, timeout=60.0)
        wall_lat = (time.monotonic() - t0) * 1000

        data = resp.json()
        verdict = str(data.get("verdict", "")).upper()
        is_pass = verdict == tc["expected"]
        status = "[PASS]" if is_pass else "[FAIL]"
        if is_pass:
            passed += 1

        latency = float(data.get("latency_ms", wall_lat))
        latencies.append(latency)
        score = float(data.get("groundedness_score", 0.0))

        resp_disp = tc["response"]
        if len(resp_disp) > 34:
            resp_disp = resp_disp[:31] + "..."

        rows.append([
            tc["id"],
            tc["name"],
            resp_disp,
            tc["expected"],
            verdict,
            f"{score:.4f}",
            status,
            f"{latency:.0f} ms",
        ])

    headers = ["ID", "Case Name", "Response Snippet", "Expected", "Actual", "Score", "Status", "Latency"]
    return {
        "headers": headers,
        "rows": rows,
        "total": len(EVAL_CASES),
        "passed": passed,
        "latencies": latencies,
    }


# ---------------------------------------------------------------------------
# Main Execution
# ---------------------------------------------------------------------------

def main() -> None:
    print("=" * 80)
    print("  Guardrail & Groundedness Test Suite")
    print(f"  Target Server: {BASE_URL}")
    print("=" * 80)
    print()

    # Pre-flight check
    if not check_server_health(BASE_URL):
        print(f"[ERROR] Cannot connect to Guardrail API server at {BASE_URL}")
        print()
        print("  Please start the server in a separate terminal before running the suite:")
        print("      cd my_project")
        print("      uvicorn main:app --reload")
        print()
        sys.exit(1)

    print("[INFO] Server health check passed (GET /health -> ok)")
    print()

    # Part 1: Guardrail Tests (Real-time checks)
    print("-" * 80)
    print("  SECTION 1: Guardrail Checks (Real-Time Policy Filter)")
    print("  Mode: Inline / Synchronous | Expected Latency: Millisecond Range (ms)")
    print("-" * 80)
    gr_results = run_guardrail_tests(BASE_URL)
    print_table(gr_results["headers"], gr_results["rows"])
    print()

    # Part 2: Evaluation Tests (Background checks)
    print("-" * 80)
    print("  SECTION 2: Context Groundedness Evaluator (Post-Hoc Verification)")
    print("  Mode: Background / Asynchronous | Expected Latency: Multi-Second Range (ms)")
    print("-" * 80)
    eval_results = run_eval_tests(BASE_URL)
    print_table(eval_results["headers"], eval_results["rows"])
    print()

    # Summary Calculations
    total_cases = gr_results["total"] + eval_results["total"]
    total_passed = gr_results["passed"] + eval_results["passed"]
    total_failed = total_cases - total_passed
    pass_rate = (total_passed / total_cases) * 100.0 if total_cases > 0 else 0.0

    gr_avg_lat = (
        sum(gr_results["latencies"]) / len(gr_results["latencies"])
        if gr_results["latencies"]
        else 0.0
    )
    eval_avg_lat = (
        sum(eval_results["latencies"]) / len(eval_results["latencies"])
        if eval_results["latencies"]
        else 0.0
    )

    print("=" * 80)
    print("  TEST SUITE SUMMARY")
    print("=" * 80)
    print(f"  Total Scenarios Run   : {total_cases}")
    print(f"  Passed                : {total_passed}")
    print(f"  Failed                : {total_failed}")
    print(f"  Overall Pass Rate     : {pass_rate:.1f}%")
    print()
    print("  Latency Benchmarks (Clearly Separated by Mode):")
    print(f"    * Guardrail Real-Time Avg Latency : {gr_avg_lat:.1f} ms")
    print(f"    * Context Eval Background Avg Lat : {eval_avg_lat:.0f} ms  ({eval_avg_lat / 1000.0:.2f} s)")
    print("=" * 80)
    print()

    if total_failed > 0:
        print(f"[FAIL] {total_failed} test scenario(s) failed.")
        sys.exit(1)
    else:
        print("[SUCCESS] All test scenarios passed successfully.")
        sys.exit(0)


if __name__ == "__main__":
    main()
